<?php

namespace App\Services;

use App\Models\Payment;
use App\Models\RentNotice;
use App\Models\Tenant;
use App\Notifications\ArrearsEscalationNotification;
use App\Notifications\RentOverdueNotification;
use Carbon\Carbon;
use Illuminate\Support\Facades\DB;

class RentReminderService
{
    public function __construct(
        protected RentStatusService $status,
        protected SmsService $sms,
    ) {}

    /**
     * Run the staged reminder / escalation workflow for all active tenants in arrears.
     * Duplicate notifications of the same type within the cooldown window are skipped.
     *
     * @return array{reminders: int, escalations: int, skipped: int}
     */
    public function run(?Carbon $date = null): array
    {
        $date = ($date ?? now())->copy()->startOfDay();
        $schedule = config('rent.reminder_schedule', []);
        $cooldown = (int) config('rent.reminder_cooldown_days', 3);

        $stats = ['reminders' => 0, 'escalations' => 0, 'skipped' => 0];

        Tenant::where('is_active', true)
            ->with(['property.landlord', 'user', 'unit'])
            ->chunkById(100, function ($tenants) use ($date, $schedule, $cooldown, &$stats) {
                foreach ($tenants as $tenant) {
                    $summary = $this->status->summary($tenant);

                    if ($summary['arrears'] <= 0 || $summary['status_key'] === 'green') {
                        continue;
                    }

                    $type = $this->stageFor($summary['max_overdue_days'], $schedule);

                    if ($type === null) {
                        continue;
                    }

                    // Serialize workers per tenant, then repeat the cooldown
                    // check while holding the lock. The notice is committed
                    // before dispatching notifications, so a concurrent run
                    // cannot create a second notice for the same stage.
                    $notice = DB::transaction(function () use ($tenant, $type, $cooldown, $date) {
                        $lockedTenant = Tenant::whereKey($tenant->id)->lockForUpdate()->first();

                        if (! $lockedTenant || $this->recentlyNotified($lockedTenant, $type, $cooldown, $date)) {
                            return null;
                        }

                        return $this->createNotice($lockedTenant, $type, $date);
                    }, 3);

                    if (! $notice) {
                        $stats['skipped']++;

                        continue;
                    }

                    $this->deliver($tenant, $summary, $type, $date, $notice);
                    $stats['reminders']++;

                    if ($type === 'escalation') {
                        $stats['escalations']++;
                    }
                }
            });

        return $stats;
    }

    /**
     * Determine the highest reminder stage reached for a given overdue duration.
     *
     * @param  array<string, int>  $schedule
     */
    protected function stageFor(int $overdueDays, array $schedule): ?string
    {
        $type = null;

        foreach ($schedule as $noticeType => $threshold) {
            if ($overdueDays >= (int) $threshold) {
                $type = $noticeType;
            }
        }

        return $type;
    }

    /**
     * Issue a reminder notice and dispatch the appropriate notifications.
     *
     * @param  array<string, mixed>  $summary
     */
    public function issue(Tenant $tenant, array $summary, string $type, Carbon $date, ?int $userId = null): RentNotice
    {
        $notice = $this->createNotice($tenant, $type, $date, $userId);
        $this->deliver($tenant, $summary, $type, $date, $notice, $userId);

        return $notice;
    }

    protected function createNotice(Tenant $tenant, string $type, Carbon $date, ?int $userId = null): RentNotice
    {
        $recipient = $tenant->email ?? $tenant->user?->email ?? $tenant->phone;

        $stage = (int) array_search($type, array_keys(config('rent.reminder_schedule', [])), true) + 1;

        $notice = RentNotice::create([
            'tenant_id' => $tenant->id,
            'type' => $type,
            'stage' => max(1, $stage),
            'issued_at' => $date->toDateString(),
            'recipient' => $recipient,
            'delivery_status' => 'sent',
            'notes' => $userId ? 'Issued manually.' : 'Auto-generated by the rent reminder workflow.',
            'created_by' => $userId,
        ]);

        return $notice;
    }

    /**
     * Send the tenant/landlord notifications and optional SMS for an issued notice.
     *
     * @param  array<string, mixed>  $summary
     */
    protected function deliver(Tenant $tenant, array $summary, string $type, Carbon $date, RentNotice $notice, ?int $userId = null): void
    {
        $paymentsSince = $this->paymentsSinceLastReminder($tenant, $notice);

        if (config('rent.notify_tenant', true) && $tenant->user) {
            $tenant->user->notify(new RentOverdueNotification($tenant, $summary, $notice, $paymentsSince));
        }

        if (config('rent.notify_landlord', true) && $tenant->property?->landlord) {
            $tenant->property->landlord->notify(new ArrearsEscalationNotification($tenant, $summary, $notice));
        }

        // Optional SMS channel (skipped automatically when no provider is set).
        $this->sms->sendTemplate(
            $type === 'escalation' ? 'arrears_notice' : 'rent_reminder',
            (string) $tenant->phone,
            [
                'name' => $tenant->full_name,
                'amount' => number_format((float) $summary['arrears'], 2),
                'due_date' => $summary['oldest_overdue']
                    ? $summary['oldest_overdue']->format('d M Y')
                    : $date->format('d M Y'),
                'days' => (string) ($summary['max_overdue_days'] ?? 0),
            ],
            ['related' => $notice, 'sent_by' => $userId],
        );

    }

    /**
     * @return array<int, array{amount: float, date: string, reference: ?string}>
     */
    protected function paymentsSinceLastReminder(Tenant $tenant, RentNotice $current): array
    {
        $previous = RentNotice::where('tenant_id', $tenant->id)
            ->whereKeyNot($current->id)
            ->latest('issued_at')
            ->first();

        if (! $previous) {
            return [];
        }

        return $tenant->payments()
            ->whereDate('payment_date', '>', $previous->issued_at->toDateString())
            ->orderBy('payment_date')
            ->get()
            ->map(fn (Payment $p) => [
                'amount' => (float) $p->amount,
                'date' => $p->payment_date->format('d M Y'),
                'reference' => $p->reference,
            ])
            ->all();
    }

    protected function recentlyNotified(Tenant $tenant, string $type, int $cooldownDays, Carbon $date): bool
    {
        return RentNotice::where('tenant_id', $tenant->id)
            ->where('type', $type)
            ->whereDate('issued_at', '>=', $date->copy()->subDays($cooldownDays)->toDateString())
            ->exists();
    }
}
